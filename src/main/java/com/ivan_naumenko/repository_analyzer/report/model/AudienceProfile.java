package com.ivan_naumenko.repository_analyzer.report.model;

import java.util.List;
import java.util.Objects;

/**
 * Описание читателя отчёта: кто он, что ему нужно, каким языком писать и
 * какие разделы включить. Разделы «Главное» и «Ограничения анализа»
 * добавляются ко всем ролям автоматически.
 *
 * <p>Разделов намеренно мало: у каждого своя задача, чтобы модели не
 * приходилось заполнять похожие разделы одной и той же мыслью.
 */
public record AudienceProfile(
        String reader,
        String goal,
        String style,
        String focus,
        List<Section> sections
) {

    public record Section(String title, String instruction) {
    }

    private static final String ACTION_FORMAT =
            "Каждый пункт: «- **[Уровень]** проблема — где (класс, файл или хэш) → "
                    + "конкретное действие». Уровни: Высокий, Средний, Низкий. Сначала "
                    + "более высокие, не больше 6 пунктов.";

    public static AudienceProfile of(ReportAudience audience) {
        Objects.requireNonNull(audience, "audience не должен быть null");
        return switch (audience) {
            case DEVELOPER -> new AudienceProfile(
                    "разработчик, который будет поддерживать и развивать этот код",
                    "быстро понять устройство проекта, ключевые компоненты, "
                            + "качество кода и места, где легко внести ошибку",
                    "технический язык с конкретными модулями, классами и файлами; "
                            + "без общих слов",
                    "архитектура, контракты, качество кода, тесты, технический долг",
                    List.of(
                            new Section(
                                    "## О проекте",
                                    "2–3 предложения: назначение, стек и главные модули "
                                            + "по СОСТОЯНИЮ КОДА."
                            ),
                            new Section(
                                    "## Архитектура",
                                    "Как устроен код и как связаны модули; что изменилось "
                                            + "в архитектуре за период — с хэшами."
                            ),
                            new Section(
                                    "## Качество кода и тесты",
                                    "Соотношение основного и тестового кода, покрыты ли "
                                            + "изменения тестами, повторяющиеся проблемы. "
                                            + "Только оценки с основанием."
                            ),
                            new Section(
                                    "## Риски и что сделать",
                                    ACTION_FORMAT
                            )
                    )
            );
            case ANALYST -> new AudienceProfile(
                    "системный или бизнес-аналитик",
                    "понять, что умеет система, какие правила, данные и сценарии "
                            + "в ней реализованы и как менялось её поведение",
                    "язык предметной области; технические детали упоминай, только "
                            + "если они влияют на поведение системы",
                    "функциональность, сценарии, бизнес-правила, данные, статусы, интеграции",
                    List.of(
                            new Section(
                                    "## О системе",
                                    "2–3 предложения: назначение, пользователи и основные сценарии."
                            ),
                            new Section(
                                    "## Возможности",
                                    "Что система умеет сейчас, сгруппировано по сценариям, "
                                            + "до 6 пунктов."
                            ),
                            new Section(
                                    "## Данные и правила",
                                    "Ключевые сущности, бизнес-правила, проверки и статусы, "
                                            + "до 6 пунктов."
                            ),
                            new Section(
                                    "## Изменения поведения",
                                    "Что поменялось для пользователей за период: этапы с хэшами. "
                                            + "Если заметных изменений нет — одна фраза."
                            ),
                            new Section(
                                    "## Вопросы к команде",
                                    "До 5 вопросов, ответы на которые нужны аналитику, чтобы "
                                            + "описать систему. Каждый — с основанием."
                            )
                    )
            );
            case SECURITY -> new AudienceProfile(
                    "специалист по информационной безопасности",
                    "оценить поверхность атаки и найти обоснованные риски для "
                            + "данных, доступа и секретов",
                    "точный язык; строго отделяй подтверждённые проблемы от гипотез; "
                            + "не называй анализ полным аудитом",
                    "точки входа, аутентификация, авторизация, валидация, секреты, "
                            + "персональные данные, зависимости",
                    List.of(
                            new Section(
                                    "## Система и точки входа",
                                    "2–3 предложения: назначение, внешние точки входа "
                                            + "(API-контроллеры, интеграции), где хранятся данные, "
                                            + "как устроена защита доступа по СОСТОЯНИЮ КОДА."
                            ),
                            new Section(
                                    "## Находки",
                                    "Каждый пункт: «- **[Подтверждено]** или **[Проверить]** "
                                            + "проблема — основание (файл, ключ конфигурации или "
                                            + "хэш) → мера защиты». [Подтверждено] — только то, что "
                                            + "прямо следует из СОСТОЯНИЯ КОДА или изменений; "
                                            + "[Проверить] — обоснованная гипотеза. Сначала "
                                            + "подтверждённые, по убыванию опасности, не больше 7 "
                                            + "пунктов. Если находок нет — «Существенных находок нет.»"
                            ),
                            new Section(
                                    "## Изменения за период",
                                    "Только изменения, которые влияют на безопасность, с хэшами. "
                                            + "Если таких нет — одна фраза."
                            )
                    )
            );
            case TEAM_LEAD -> new AudienceProfile(
                    "тимлид команды разработки",
                    "оценить состояние кодовой базы и процесса разработки и "
                            + "определить приоритеты команды",
                    "управленческо-технический язык: факт, оценка, приоритет",
                    "направления работы, архитектура, технический долг, тесты, "
                            + "процесс, риски поставки",
                    List.of(
                            new Section(
                                    "## О проекте",
                                    "2 предложения: назначение и текущее состояние."
                            ),
                            new Section(
                                    "## Направления работы",
                                    "Над чем работала команда и какая доля усилий куда ушла — "
                                            + "по характеру изменений из ФАКТОВ."
                            ),
                            new Section(
                                    "## Состояние кода и процесса",
                                    "Архитектура и долг, тесты, размер коммитов, понятность "
                                            + "сообщений — оценки с основанием, до 5 пунктов."
                            ),
                            new Section(
                                    "## Риски и приоритеты",
                                    "Нумерованный список до 5 пунктов по убыванию важности: "
                                            + "«проблема — основание (файл или хэш) → шаг для команды»."
                            )
                    )
            );
            case DIRECTOR -> new AudienceProfile(
                    "руководитель без глубокой технической подготовки",
                    "понять, что создано, насколько продукт устойчив и какие "
                            + "решения от него требуются",
                    "простой деловой язык без жаргона; неизбежные термины поясняй "
                            + "в скобках; не больше 3 пунктов в разделе",
                    "результаты, ценность для пользователей, устойчивость, риски для "
                            + "бизнеса, необходимые решения",
                    List.of(
                            new Section(
                                    "## О продукте",
                                    "1–2 предложения: что это и какую задачу решает."
                            ),
                            new Section(
                                    "## Результаты",
                                    "Что сделано за период и в каком темпе — по ФАКТАМ."
                            ),
                            new Section(
                                    "## Риски и решения",
                                    "До 3 пунктов: «риск — чем грозит бизнесу → какое решение "
                                            + "нужно от руководителя». Если серьёзных рисков нет — "
                                            + "одна фраза."
                            )
                    )
            );
        };
    }
}
