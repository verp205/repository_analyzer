    private final CompactContextSerializer serializer;

    public String build(
            CompactCommitContext context,
            ReportAudience audience
    ) {
        Objects.requireNonNull(context, "context не должен быть null");
        Objects.requireNonNull(audience, "audience не должен быть null");

        String contextJson = serializer.serialize(context);

        return """
                PROMPT_VERSION: %s

                BASE_TASK:
                %s

                AUDIENCE_INSTRUCTION:
                %s

                RULES:
                %s

                OUTPUT_FORMAT:
                %s

                <TECHNICAL_CONTEXT>
                %s
                </TECHNICAL_CONTEXT>
                """.formatted(
                PROMPT_VERSION,
                BASE_TASK,
                instructionFor(audience),
                COMMON_RULES,
                OUTPUT_FORMAT,
                contextJson
        );
    }

